  // PRETTYPRINTING

  private boolean isLeftBracket(Lexem lexem) {
    return isOne(lexem, Lexem.Lbrack, Lexem.Lparenth, Lexem.Lset, Lexem.Lgroup);
  }

  private boolean isRightBracket(Lexem lexem) {
    // case Rbag:
    return isOne(lexem, Lexem.Rbrack, Lexem.Rparenth, Lexem.Rset, Lexem.Rgroup);
  }

  private boolean isStroke(Lexem lexem) {
    return isOne(lexem, Lexem.StrokeIn, Lexem.StrokeOut, Lexem.StrokePrime)
      || lexem instanceof Lexem.StrokeIndex;
  }

  private boolean isPunctuation(Lexem lexem) {
    return isOne(lexem, Lexem.Dot, Lexem.Comma, Lexem.Colon, Lexem.Semi);
  }

  private boolean isIdentifier(Text text) {
    switch (text) {
      case Text.ZedToken t -> {
        Lexem lexem = t.lexem;
        if (isPunctuation(lexem) ||
            isLeftBracket(lexem) ||
            isRightBracket(lexem) ||
            isStroke(lexem))
          return false;
        if (lexem instanceof Lexem.Word) {
          return true;
        } else {
          String word = getRepr(lexem);
          if (word.length() > 0 && word.charAt(0) == '\\')
            return true;
        }
      }
      case Text.Literal t -> {
        return true;
      }
      default -> { }
    }
    return false;
  }

  private boolean isGraphem(Text text) {
    String word;

    if (isIdentifier(text))
      return false;
    switch (text) {
      case Text.ZedToken t -> {
        Lexem lexem = t.lexem;
        if (isLeftBracket(lexem) ||
            isRightBracket(lexem) ||
            isPunctuation(lexem))
          return false;
        word = getRepr(lexem);
      }
      case Text.Literal t -> word = t.contents;
      default -> {
        return false;
      }
    }
    return
      (word.length() > 0 &&
       !(Character.isLetterOrDigit(word.charAt(0)) ||
         Character.isLetterOrDigit(word.charAt(word.length() - 1))));
  }

  /** */
  public boolean needSpaceBetween(Text left, Text right) {
    // FIXME -- additional conditions?
    left:
    if (left instanceof Text.ZedToken t) {
      Lexem lexem = t.lexem;
      // no space after opening bracket
      if (isLeftBracket(lexem))
        break left;
      // space after closing bracket before identifiers
      if (isRightBracket(lexem) && isIdentifier(right))
        return true;
      if (isOne(lexem, Lexem.Dot, Lexem.Comma))
        break left;
      if (isOne(lexem, Lexem.Spot, Lexem.Mid, Lexem.Colon, Lexem.Semi,
                Lexem.True, Lexem.False,
                Lexem.Data,          // NO EFFECT??? Robert
                Lexem.Port, Lexem.Property))
        return true;
      if (isGraphem(left))
        return true;
    }
    right:
    if (right instanceof Text.ZedToken t) {
      Lexem lexem = t.lexem;
      if (isPunctuation(lexem))
        break right;
      if (isStroke(lexem))
        break right;
      if (isRightBracket(lexem))
        break right;
      if (isLeftBracket(lexem) && isIdentifier(left))
        return true;
      if (isOne(lexem, Lexem.Spot, Lexem.Mid, Lexem.True, Lexem.False))
        return true;
      if (isGraphem(right))
        return true;
    }
    if (isIdentifier(left) && isIdentifier(right))
      return true;
    return false;
  }

  protected boolean needBreakBetween(Text left, Text right) {
    /*
      case ZedToken(Linesep):
        return true;
    */
    if (left instanceof Text.ZedMarkup)
      return true;
    if (right instanceof Text.ZedMarkup)
      return true;
    return false;
  }

