  /** The table row of a nullary lexem. */
  private static Lexis lexisOf(Lexem lexem) {
    Lexis row = lexis.get(lexem.zeta$content$text$Lexem$$tag);
    if (row == null) throw FatalError.unexpectedCase("lexem");
    return row;
  }

  /** Whether the lexem is one of the given constants (Pizza's `case A: case B:`). */
  private static boolean isOne(Lexem lexem, Lexem... constants) {
    for (Lexem c : constants) {
      if (lexem.zeta$content$text$Lexem$$tag == c.zeta$content$text$Lexem$$tag)
        return true;
    }
    return false;
  }

  /** Whether the markup kind is the given constant. */
  private static boolean kindIs(Text.ZedMarkupKind kind, Text.ZedMarkupKind constant) {
    return kind.zeta$content$text$Text$ZedMarkupKind$$tag
      == constant.zeta$content$text$Text$ZedMarkupKind$$tag;
  }

  /** */
  public String getRepr(Lexem lexem) {
    return switch (lexem) {
      case Lexem.Number l -> l.image.toString();
      case Lexem.Denotation l -> makeDenotation(l.image.toString());
      case Lexem.StrokeIndex l -> l.image.toString();
      case Lexem.Word l -> l.image.toString();
      case Lexem.Keyword l -> l.image.toString();
      case Lexem.Lkeyword l -> l.image.toString();
      case Lexem.Rkeyword l -> l.image.toString();
      case Lexem.Pkeyword l -> l.image.toString();
      case Lexem.SimpleName l -> l.image.toString();
      case Lexem.MacroArg l -> l.image.toString();
      default -> lexisOf(lexem).repr();
    };
  }

  private String makeDenotation(String s) {
    int l = s.length();
    StringBuffer res = new StringBuffer("\\ZD{");
    for (int i = 0; i < l; i++) {
      char c = s.charAt(i);
      switch (c) {
        case '{': case '}': case '\\': case '"':
          res.append('\\');
          res.append(c);
          break;
        case '\n':
          res.append("\\n");
          break;
        case '\r':
          res.append("\\r");
          break;
        case '\t':
          res.append("\\t");
          break;
        case '\f':
          res.append("\\f");
          break;
        case '\b':
          res.append("\\b");
          break;
        default:
          res.append(c);
      }
    }
    res.append('}');
    return res.toString();
  }

  /** Whether the lexem carries an image (is not one of the table's nullary lexems). */
  private static boolean hasImage(Lexem lexem) {
    return lexem instanceof Lexem.Number || lexem instanceof Lexem.Denotation
      || lexem instanceof Lexem.StrokeIndex || lexem instanceof Lexem.Word
      || lexem instanceof Lexem.Keyword || lexem instanceof Lexem.Lkeyword
      || lexem instanceof Lexem.Rkeyword || lexem instanceof Lexem.Pkeyword
      || lexem instanceof Lexem.SimpleName || lexem instanceof Lexem.MacroArg;
  }

  /** */
  public boolean isLeftOffside(Lexem lexem) {
    if (leftOffside.contains(lexem)) {
      return true;
    } else {
      // all ten image-carrying lexems are `res = false` in the genlexis table
      return hasImage(lexem) ? false : lexisOf(lexem).leftOffside();
    }
  }

  /** */
  public boolean isRightOffside(Lexem lexem) {
    if (rightOffside.contains(lexem)) {
      return true;
    } else {
      // all ten image-carrying lexems are `res = false` in the genlexis table
      return hasImage(lexem) ? false : lexisOf(lexem).rightOffside();
    }
  }

