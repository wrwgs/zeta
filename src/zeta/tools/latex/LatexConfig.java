/**
 * Configurations of the LaTeX concrete language. <p>
 *
 * @version $Id: LatexConfig.pizza,v 1.10 2000/07/06 09:18:24 wg Exp $
 *
 * <h2>Port notes</h2>
 *
 * This class is the `lang-config` content of every LaTeX unit and drives `pretty-text`, so
 * its rendering and its tables are covered by the oracle.  The public constructor is ABI:
 * `zeta.tools.util.ZirpUtil` and `zeta.tools.pp.PrettyPrinterAdaptor` construct it.
 *
 * <b>The three lexis tables.</b>  `getRepr`, `isLeftOffside` and `isRightOffside` were each a
 * 106-arm `switch` generated by genlexis (`@@TOSTRING`, `@@LEFTOFFSIDE`, `@@RIGHTOFFSIDE`).
 * Here the 96 nullary lexems are one table, one row per lexem with its representation and
 * its two offside flags, transcribed from those three switches; the ten lexems carrying an
 * image are type patterns.  The table is keyed by the lexem's `$$tag`, read from the
 * constant itself, because a Pizza `switch` over constants dispatches on the tag -- so no
 * tag value is written down here.  A lexem the table does not know raised `new Error()`
 * (Pizza's fall-off for a non-exhaustive switch); it raises `FatalError.unexpectedCase`.
 *
 * PORT CHANGE (skew): the source's `getRepr` returns a `Denotation`'s image as is, with a
 * note that it must be modified "after genlexis" to go through `makeDenotation`.  The 2002
 * class has that modification (`getRepr` calls `makeDenotation` for `Denotation`), so the
 * port does too.
 *
 * The other constant-case switches (`case Dot:`, `case Unboxed:` ...) compare tags for the
 * same reason, via {@link #isOne} and {@link #kindIs}.
 *
 * `writeObject`'s closure over the markup map became a loop over its enumeration, which
 * visits the pairs in the same order.  The field initialisers keep their order, since the
 * order of `include`/`define` on an `agl` hash collection decides its iteration order, and
 * `toFormat` (the `lang-config` artifact) renders the collections in that order.
 */
