#!/bin/sh
# Regenerate the zeta.tools.zparser parser from its grammar.
#
#   harness/gen-parser-zparser.sh
#
# Input:  grammar/zeta/tools/zparser/ItemParser.jj  (the ported grammar, Java actions)
# Output: src/zeta/tools/zparser/{ItemParser,ItemParserConstants,Token,TokenManager,
#         ParseException,TokenMgrError}.java  -- generated, checked in, never hand-edited.
#
# The grammar sets USER_TOKEN_MANAGER, so JavaCC emits only the TokenManager interface;
# the token manager itself is the hand-written TextTokenManager.java, which this script does
# not touch.
#
# Generator: JavaCC 3.2, the version the project uses (zesurrect-plan.md 3.1).  The 2002
# classes were generated by JavaCC 2.1, whose output we cannot reproduce, so 3.2's output was
# checked against them: identical token constants and token images, identical jj_la1 choice
# tables, the same 43 syntactic lookaheads and 12 semantic-lookahead sites, and the same
# runtime routines (jj_consume_token, getToken, jj_ntk, jj_add_error_token,
# generateParseException, jj_save) -- with ONE behavioural difference, repaired below.
#
# The repair.  2.1 signalled "lookahead limit reached" by returning false up the jj_3
# routines; 3.2 throws ItemParser$LookaheadSuccess from jj_scan_token instead, and catches it
# in every jj_2_N.  But jj_rescan_token -- run by generateParseException to collect the
# "expected one of" alternatives for a syntax error -- calls the jj_3_N routines directly,
# with no handler, so on some syntax errors the exception escaped the parser and the error
# diagnostic was lost (found by differential testing against the 2002 parser).  Later
# JavaCC releases added a handler there.  This script adds one around each single rescan
# call, which is exactly 2.1's behaviour: the routine stops, and the rescan goes on with the
# next saved call.  (JavaCC 4+ wraps the whole per-lookahead chain instead, which would skip
# the chain's remaining calls -- not what 2.1 did.)
#
# Idempotent: generates into a fresh temporary directory and copies over.
set -e
ZETA=$(cd "$(dirname "$0")/.." && pwd)
JAVA=$ZETA/toolchain/jdk21/bin/java
JAVACC_JAR=$ZETA/toolchain/javacc/javacc-3.2.jar
GRAMMAR=$ZETA/grammar/zeta/tools/zparser/ItemParser.jj
OUT=$ZETA/src/zeta/tools/zparser
FILES="ItemParser ItemParserConstants Token TokenManager ParseException TokenMgrError"

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

"$JAVA" -cp "$JAVACC_JAR" javacc -OUTPUT_DIRECTORY="$TMP" "$GRAMMAR" >"$TMP/javacc.log" 2>&1 || {
  cat "$TMP/javacc.log"; exit 1; }
grep -q "Parser generated successfully" "$TMP/javacc.log" || { cat "$TMP/javacc.log"; exit 1; }
grep -i "warning" "$TMP/javacc.log" && { echo "javacc reported warnings" >&2; exit 1; }

# The rescan repair (see above).  Fails unless the expected code is found exactly once.
python3 -I - "$TMP/ItemParser.java" <<'EOF'
import re, sys
path = sys.argv[1]
src = open(path, encoding="latin1").read()
pat = re.compile(r"(?P<ind>[ \t]*)switch \(i\) \{\n"
                 r"(?P<body>(?:[ \t]*case \d+: jj_3_\d+\(\); break;\n)+)"
                 r"(?P=ind)\}\n")
found = pat.findall(src)
if len(found) != 1 or "final private void jj_rescan_token()" not in src:
    sys.exit("gen-parser-zparser.sh: jj_rescan_token switch not found exactly once")
def fix(m):
    ind = m.group("ind")
    body = "".join("  " + l + "\n" for l in m.group("body").splitlines())
    return (ind + "// gen-parser-zparser.sh: catch LookaheadSuccess per rescan call, as\n"
            + ind + "// JavaCC 2.1 (which generated the 2002 parser) in effect did.\n"
            + ind + "try {\n"
            + ind + "  switch (i) {\n" + body + ind + "  }\n"
            + ind + "} catch (LookaheadSuccess ls) { }\n")
src = pat.sub(fix, src, count=1)
open(path, "w", encoding="latin1").write(src)
EOF

for f in $FILES; do
  [ -f "$TMP/$f.java" ] || { echo "missing generated $f.java" >&2; exit 1; }
done
for f in $FILES; do
  cp "$TMP/$f.java" "$OUT/$f.java"
done
echo "generated $(echo $FILES | wc -w) file(s) into $OUT"
