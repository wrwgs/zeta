#!/usr/bin/env python3
"""Targeted negative tests: one minimal specification per checker diagnostic.

Generic mutation of the real specifications (harness/negtest.py) reaches only 4 of the 25
diagnostic kinds, and that is near its ceiling -- renaming, duplicating and retyping
declarations can essentially only produce the undeclared / redeclaration / type-mismatch
families.  The rest need purpose-built inputs, written from the grammar
(src/tools/zparser/ItemParser.jj), the checker's call sites, and the toolkit.

Each case below is a minimal ZETA document that should elicit exactly one diagnostic kind.
`expect` names the kind; `None` means "no diagnostic expected" (a positive control, to catch a
case that fails for an unintended reason).  The runner reports, per case, which kinds actually
fired, so a case that elicits the wrong diagnostic is visible rather than silently counted.

Usage:  targeted.py --run [--only <kind>,...]      # writes tests/targeted/, reports coverage
"""
import argparse
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import canonicalize                                                   # noqa: E402
import negtest                                                        # noqa: E402

ZETA = os.path.dirname(HERE)
TESTS = os.path.join(ZETA, "tests/targeted")
WORK = os.path.join(ZETA, "work/targeted")

DOC = r"""\documentclass{article}
\usepackage{zeta}
\begin{document}
%% Targeted negative test: expect diagnostic kind `%(kind)s'.
%% Generated by harness/targeted.py -- see that file for the rationale.
\begin{zdirectives}
  \zsection%(parents)s{%(unit)s}
\end{zdirectives}
%(body)s
\end{document}
"""

