def run_case(name, expect, parents, body, extra, cat, classes=None):
    unit = "T" + name.replace("-", "")
    texname = "%s.tex" % unit
    tex = DOC % {"kind": expect or "none", "parents": parents, "unit": unit, "body": body}

    tdir = os.path.join(TESTS, name)
    os.makedirs(tdir, exist_ok=True)
    with open(os.path.join(tdir, texname), "w", encoding="latin-1") as f:
        f.write(tex)

    work = os.path.join(WORK, name)
    shutil.rmtree(work, ignore_errors=True)
    os.makedirs(work)
    shutil.copy(os.path.join(tdir, texname), work)
    for fn, content in (extra or {}).items():
        with open(os.path.join(tdir, fn), "w", encoding="latin-1") as f:
            f.write(content)
        shutil.copy(os.path.join(tdir, fn), work)

    out = subprocess.run(
        [sys.executable, "-I", os.path.join(HERE, "zdrive.py"), "--cwd", work,
         *(["--classes", classes] if classes else []),
         *(["load " + fn for fn in sorted(extra or {})]),
         "load " + texname, "c -u %s#%s" % (unit, unit)],
        capture_output=True, text=True, timeout=600).stdout

    diags = negtest.diagnostics(out)
    kinds = sorted({k for k in (negtest.classify(d, cat) for d in diags) if k})
    exp = canonicalize.canon_transcript(out, session_dir=work)
    verdict = {"expect": expect, "kinds": kinds, "diagnostics": diags[:6]}

    if expect is None:
        status = "ok" if not diags else "UNEXPECTED-DIAG"
    elif expect in kinds:
        status = "HIT" if kinds == [expect] else "hit+extra"
    elif kinds:
        status = "WRONG-KIND"
    else:
        status = "NO-DIAG"
    return status, kinds, diags, exp, verdict


def compare(tdir, exp, verdict):
    """Compare a freshly produced transcript and verdict with the recorded ones.

    Returns a short note naming what moved, or None.  The verdict is compared on the fields
    that are a claim about the system -- which diagnostic kinds came out -- and not on
    `diagnostics`, whose text includes source locators that a mutation can shift without the
    classification changing.
    """
    notes = []
    path = os.path.join(tdir, "exp")
    if not os.path.exists(path):
        return "NO RECORDING"
    if open(path, encoding="latin-1").read() != exp:
        notes.append("transcript")
    path = os.path.join(tdir, "verdict.json")
    if os.path.exists(path):
        with open(path) as f:
            was = json.load(f)
        if was.get("kinds") != verdict.get("kinds"):
            notes.append("kinds %s -> %s" % (was.get("kinds"), verdict.get("kinds")))
        if was.get("verdict") != verdict.get("verdict"):
            notes.append("verdict %s -> %s" % (was.get("verdict"), verdict.get("verdict")))
    return "DIFFERS: " + "; ".join(notes) if notes else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", action="store_true",
                    help="run the cases and RECORD exp/verdict.json (this is the update mode)")
    ap.add_argument("--check", action="store_true",
                    help="run the cases and COMPARE against the recorded exp/verdict.json; "
                         "non-zero exit on any difference.  With --classes this is the gate "
                         "for a ported build.")
    ap.add_argument("--classes", default=None,
                    help="class tree(s) to run against, e.g. classes")
    ap.add_argument("--runs", type=int, default=3,
                    help="runs per case for --run; a recording is kept only if all of them "
                         "agree (default 3).  Same rule as baseline.py --update, and for the "
                         "same reason: `cyclic` reports the cycle from either end under the "
                         "reference build, so a single run can record an unlucky sample and "
                         "then fail every later check.")
    ap.add_argument("--only", default=None)
    args = ap.parse_args()
    if not (args.run or args.check):
        ap.error("use --run (record) or --check (compare)")
    cat = negtest.catalogue()
    wanted = set(args.only.split(",")) if args.only else None

    hits, differed, unstable = set(), [], []
    for name, expect, parents, body, extra in CASES:
        if wanted and name not in wanted:
            continue
        status, kinds, diags, exp, verdict = run_case(
            name, expect, parents, body, extra, cat, args.classes)
        tdir = os.path.join(TESTS, name)
        if args.check:
            note = compare(tdir, exp, verdict)
            if note:
                differed.append((name, note))
        else:
            agree = True
            for _i in range(max(0, args.runs - 1)):
                again = run_case(name, expect, parents, body, extra, cat, args.classes)
                if again[3] != exp or again[4].get("kinds") != verdict.get("kinds"):
                    agree = False
                    break
            if agree:
                with open(os.path.join(tdir, "exp"), "w", encoding="latin-1") as f:
                    f.write(exp)
                with open(os.path.join(tdir, "verdict.json"), "w") as f:
                    json.dump(verdict, f, indent=2)
                note = None
            else:
                note = "UNSTABLE over %d runs -- recording left untouched" % args.runs
                unstable.append(name)
        print("  %-30s %-16s %-44s %s"
              % (name, status, ",".join(kinds) or "-", note or ""))
        if status in ("WRONG-KIND", "NO-DIAG", "UNEXPECTED-DIAG"):
            for d in diags[:2]:
                print("       %s" % d[:110])
        hits |= set(kinds)
    print("\nkinds elicited by targeted cases: %d  (%s)" % (len(hits), ",".join(sorted(hits))))
    if args.check:
        print("%d of %d case(s) differ from the recording" % (len(differed), len(CASES)))
        return 1 if differed else 0
    if unstable:
        print("%d case(s) not reproducible on this build: %s" % (len(unstable),
                                                                 ", ".join(unstable)))
    return 1 if unstable else 0


if __name__ == "__main__":
    sys.exit(main())
